"""Generate docs/CATALOG.md from the library and config/reference.yaml.

uv run python scripts/gen_catalog.py          write it
uv run python scripts/gen_catalog.py --check  exit 1 if it's stale (used by the tests)
"""

import sys
from pathlib import Path

from rigsmith import config, library  # noqa: F401
from rigsmith.backends import Apt, Brew, Cask, GitClone, Krew, NerdFont, Release, Script, UvTool, VSCodeExt

OUT = Path(__file__).resolve().parents[1] / "docs/CATALOG.md"
KIND = {
    Brew: "brew",
    Cask: "cask",
    Apt: "apt",
    Krew: "krew",
    VSCodeExt: "VS Code",
    UvTool: "uv tool",
    NerdFont: "Nerd Font",
    Release: "release",
    Script: "script",
    GitClone: "git",
}


def how(art) -> str:
    parts = []
    for s in art.sources:
        name = s.pkg if type(s) not in (Script, GitClone) else ""
        where = f" ({s.os})" if s.os else ""
        parts.append(f"{KIND[type(s)]} {f'`{name}`' if name else ''}{where}".strip())
    if art.snippets:
        parts.append("zsh snippet")
    if art.settings:
        parts.append(f"{len(art.settings)} setting{'s' * (len(art.settings) > 1)}")
    if art.files:
        parts.append("file")
    return " · ".join(parts)


def render() -> str:
    ref = config.load("reference")
    sections = list(dict.fromkeys(e.section for e in ref.entries))
    lines = [
        "# Catalog",
        "",
        "<!-- generated by scripts/gen_catalog.py: edit the library, not this file -->",
        "",
        f"**{len(ref.entries)} artifacts** in {len(sections)} sections. Profiles are cumulative: "
        + " ⊂ ".join(f"`{p}`" for p in ref.profiles)
        + ". ◉ marks a role: only one provider is active at a time.",
        "",
        " · ".join(f"[{s}](#{s})" for s in sections),
        "",
    ]
    for sec in sections:
        lines += [f"## {sec}", "", "| | artifact | profile | what it is | installed with |", "|---|---|---|---|---|"]
        last = None
        for e in (e for e in ref.entries if e.section == sec):
            art = ref.library[e.id]
            sub = f"**{e.subsection}**" if e.subsection != last else ""
            last = e.subsection
            role = f"◉ {art.role}" if art.role else ""
            about = art.help.replace("|", "\\|")
            lines.append(f"| {sub} | `{e.id}` {role} | {e.profile} | {about} | {how(art)} |")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("docs/CATALOG.md is stale: run `uv run python scripts/gen_catalog.py`")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT}")
